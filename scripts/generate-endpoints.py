def pascal(name):
    words = re.findall(r"[a-zA-Z0-9]+", re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name))
    value = "".join(ACRONYMS.get(word.lower(), word[0].upper() + word[1:]) for word in words)
    return value if value and value[0].isalpha() else "Field" + value


def camel(name):
    value = pascal(name)
    value = value[0].lower() + value[1:]
    return "@" + value if value in {"event", "params", "object", "class", "string", "namespace"} else value


def literal(value):
    return json.dumps(value, ensure_ascii=True)


def group_name(tag):
    return RENAMED_GROUPS.get(tag, pascal(tag.removeprefix("activities.")))


def method_name(tag, operation_id):
    return RENAMED_METHODS.get(operation_id, pascal(operation_id.removeprefix(tag + "_"))) + "Async"


def literal_shape(value):
    if isinstance(value, dict):
        # Lookup tables contain keys specific to the example's organization.
        if value and all(re.match(r"^(?:user|orga|lead|cont|oppo|stat|cf|acti|role)_.+|^\d{4}-\d{2}-\d{2}$", k) for k in value):
            return {"type": "object", "additionalProperties": True}
        return {"type": "object", "properties": {k: literal_shape(v) for k, v in value.items()
                                                  if not k.startswith("custom.")}}
    if isinstance(value, list):
        return {"type": "array", "items": merge_shapes([literal_shape(entry) for entry in value])}
    if isinstance(value, bool):
        return {"type": "boolean"}
    if isinstance(value, int):
        return {"type": "integer"}
    if isinstance(value, float):
        return {"type": "number"}
    if isinstance(value, str):
        return {"type": "string"}
    return {}


def merge_shapes(shapes):
    shapes = [shape for shape in shapes if shape]
    if not shapes:
        return {}
    if all(shape == shapes[0] for shape in shapes):
        return shapes[0]
    kinds = {shape.get("type") for shape in shapes}
    if kinds == {"object"} and all("properties" in shape for shape in shapes):
        keys = sorted({key for shape in shapes for key in shape["properties"]})
        return {"type": "object", "properties": {
            key: merge_shapes([shape["properties"].get(key, {}) for shape in shapes]) for key in keys
        }}
    if kinds == {"array"}:
        return {"type": "array", "items": merge_shapes([shape.get("items", {}) for shape in shapes])}
    if kinds <= {"integer", "number"}:
        return {"type": "number"}
    return {}


def content_shape(content):
    if "schema" in content:
        return content["schema"]
    examples = [item["value"] for item in content.get("examples", {}).values() if "value" in item]
    if "example" in content:
        examples.append(content["example"])
    return merge_shapes([literal_shape(example) for example in examples])


class Models:
    def __init__(self, components):
        self.components = components
        self.classes = {}
        self.generated = {}
        self.register = {"JsonElement"}
        self.optional_fields = set()
        self.patch_components = set()

    def shape_type(self, shape, name, patch=False):
        if "$ref" in shape:
            ref = shape["$ref"].rsplit("/", 1)[1]
            return self.shape_type(self.components[ref], pascal(ref), ref in self.patch_components)
        if "oneOf" in shape or "anyOf" in shape:
            choices = [item for item in shape.get("oneOf", shape.get("anyOf", [])) if item.get("type") != "null"]
            if len(choices) == 1:
                return self.shape_type(choices[0], name, patch)
            if choices and all(choice.get("type") == "string" for choice in choices):
                return "string"
            return "JsonElement"

        kind = shape.get("type")
        if isinstance(kind, list):
            kinds = [kind for kind in kind if kind != "null"]
            kind = kinds[0] if len(kinds) == 1 else None
        if kind == "string":
            return {"date-time": "DateTimeOffset", "date": "DateOnly"}.get(shape.get("format"), "string")
        if kind == "integer":
            return "int" if shape.get("format") == "int32" else "long"
        if kind == "number":
            return "decimal"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"IReadOnlyList<{self.shape_type(shape.get('items', {}), name + 'Item')}>"
        if "properties" in shape and shape["properties"]:
            return self.object_type(shape, name, patch)
        if kind == "object" and isinstance(shape.get("additionalProperties"), dict):
            item = self.shape_type(shape["additionalProperties"], name + "Value")
            return f"IReadOnlyDictionary<string, {item}>"
        return "JsonElement"

    def object_type(self, shape, name, patch):
        key = (name, json.dumps(shape, sort_keys=True), patch)
        if key in self.generated:
            return self.generated[key]

        unique = name
        suffix = 2
        while unique in self.classes:
            unique = f"{name}{suffix}"
            suffix += 1
        result = "ApiModels." + unique
        self.generated[key] = result
        self.classes[unique] = None
        properties = []
        used_names = {unique, "AdditionalFields"}
        schemas = {wire: schema for wire, schema in shape["properties"].items() if not wire.startswith("custom.")}
        legacy = {
            LEGACY_CUSTOM_FIELD_IDS[index]: ({"type": kind, "items": {"type": "string"}} if kind == "array"
                                             else {"type": kind} if kind else {})
            for index, kind in LEGACY_CUSTOM_FIELDS.get(unique, {}).items()
        }
        schemas.update(legacy)
        for wire, schema in sorted(schemas.items()):
            prop = pascal(wire)
            while prop in used_names:
                prop += "Value"
            used_names.add(prop)
            value_type = self.shape_type(schema, unique + prop)
            constant = schema.get("const")
            notes = [f'    /// <summary>The <c>{html.escape(wire)}</c> field.</summary>',
                     f"    [JsonPropertyName({literal(wire)})]"]
            if wire in legacy:
                notes[0] = "    /// <summary>1.0 compatibility property for a field from a Close example payload.</summary>"
                notes[1:1] = ["    /// <exclude />", "    [EditorBrowsable(EditorBrowsableState.Never)]"]
            initialized = ""
            if isinstance(constant, str) and value_type == "string":
                initialized = " = " + literal(constant) + ";"
                field_type = "string"
            elif patch:
                field_type = f"CloseField<{value_type}?>"
                self.optional_fields.add(value_type)
                notes.append("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]")
            else:
                field_type = value_type + "?"
            notes.append(f"    public {field_type} {prop} {{ get; init; }}{initialized}")
            properties.append("\n".join(notes))
        properties.append(
            "    /// <summary>Additional fields in the Close payload.</summary>\n"
            "    [JsonExtensionData]\n"
            "    public Dictionary<string, JsonElement>? AdditionalFields { get; set; }"
        )
        if unique in CUSTOM_FIELD_REQUESTS:
            properties.append(
                '    /// <summary>Sets an organization-defined field. Supply a JSON null to clear it in an update.</summary>\n'
                '    public void SetCustomField(string fieldId, JsonElement value) =>\n'
                '        (AdditionalFields ??= new(StringComparer.Ordinal))[CloseObject.CustomFieldName(fieldId)] = value.Clone();'
            )
        if unique in CUSTOM_FIELD_RESPONSES:
            properties.append(self.custom_field_reader(legacy))
        self.classes[unique] = (
            f"/// <summary>Fields in the Close {unique} payload.</summary>\n"
            f"public sealed class {unique}\n{{\n" + "\n\n".join(properties) + "\n}"
        )
        return result

    def custom_field_reader(self, legacy):
        documentation = "    /// <summary>Gets an organization-defined field by its Close cf_ identifier.</summary>\n"
        signature = "    public bool TryGetCustomField(string fieldId, out JsonElement value)"
        if not legacy:
            return documentation + signature + " => CloseObject.TryReadCustomField(AdditionalFields, fieldId, out value);"
        checks = [
            f"            case {literal(wire)} when {pascal(wire)} is {{ }} previous:\n"
            f"                value = JsonSerializer.SerializeToElement(previous, EndpointJson.Type<"
            f"{'IReadOnlyList<string>' if schema.get('type') == 'array' else 'string'}>());\n"
            "                return true;"
            for wire, schema in sorted(legacy.items())
        ]
        return (documentation + signature + "\n    {\n"
                "        if (CloseObject.TryReadCustomField(AdditionalFields, fieldId, out value)) return true;\n"
                "        switch (CloseObject.CustomFieldName(fieldId))\n        {\n" + "\n".join(checks)
                + "\n            default: return false;\n        }\n    }")

    def contract(self, schema, name, patch=False):
        field = self.shape_type(schema, name, patch)
        self.register.add(field)
        return field

    def json_context(self):
        declarations = self.register | {"string", "IReadOnlyList<string>"}
        for item in self.optional_fields:
            declarations.add(item + "?" if item in {"bool", "int", "long", "decimal", "DateOnly", "DateTimeOffset", "JsonElement"} else item)
        converters = ["typeof(CloseTimestampConverter)"] + [
            f"typeof(CloseFieldConverter<{item}?>)" for item in sorted(self.optional_fields)
        ]
        return (
            HEADER + "using System.Text.Json;\nusing System.Text.Json.Serialization;\n"
            "using System.Text.Json.Serialization.Metadata;\nusing ApiModels = Close.DotNet.Models;\n\n"
            "namespace Close.DotNet;\n\n"
            "[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.SnakeCaseLower,\n"
            "    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,\n"
            "    GenerationMode = JsonSourceGenerationMode.Metadata,\n"
            "    Converters = [" + ",\n        ".join(converters) + "])]\n" +
            "\n".join(f"[JsonSerializable(typeof({item}))]" for item in sorted(declarations)) +
            "\ninternal sealed partial class EndpointJson : JsonSerializerContext\n{\n"
            "    internal static JsonTypeInfo<T> Type<T>() => (JsonTypeInfo<T>)Default.Options.GetTypeInfo(typeof(T));\n}\n"
        )

    def records(self):
        return (
            HEADER + "using System.ComponentModel;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n"
            "using ApiModels = Close.DotNet.Models;\n\nnamespace Close.DotNet.Models;\n\n" +
            "\n\n".join(self.classes[name] for name in sorted(self.classes)) + "\n"
        )


def operations(spec, rows):
    for row in rows:
        route = row["route"]
        verb = row["method"]
        op = spec["paths"][route][verb.lower()]
        if op["operationId"] != row["operation_id"]:
            raise SystemExit(f"Coverage inventory does not match the operation at {verb} {route}.")
        yield row, op


def build_operation(row, op, models, query_options):
    tag, verb, route, operation_id, reference = (row[key] for key in ("resource", "method", "route", "operation_id", "reference"))
    group = group_name(tag)
    method = method_name(tag, operation_id)
    name = group + method.removesuffix("Async")
    success = next((v for status, v in op["responses"].items() if status in {"200", "201"}), None)
    response_shape = content_shape(success.get("content", {}).get("application/json", {})) if success is not None else {}
    response_fields = response_shape.get("properties", {})
    documented_parameters = {p.get("name") for p in op.get("parameters", [])}
    is_offset_list = (
        verb == "GET" and method.startswith("List") and {"_skip", "_limit"} <= documented_parameters
        and set(response_fields) == {"data", "has_more"} and response_fields["data"].get("type") == "array"
    )
    filter_type = query_options.add_operation(row, op, is_offset_list)
    stream_method = method
    if is_offset_list:
        method = method.removesuffix("Async") + "PageAsync"
    variables = re.findall(r"\{([^{}]+)\}", route)
    relative = route.removeprefix("/")
    for variable in variables:
        relative = relative.replace("{" + variable + "}", "{CloseRoutes.Segment(" + camel(variable) + ")}")
    path = ("$" if variables else "") + '"' + relative + '"'

    required_query = [p["name"] for p in op.get("parameters", []) if p.get("in") == "query" and p.get("required")]
    parameters = [f"string {camel(param)}" for param in variables + required_query]
    test_args = [literal("test_" + param) for param in variables + required_query]
    request = op.get("requestBody", {}).get("content", {}).get("application/json", {})
    if request:
        request_type = models.contract(content_shape(request), name + "Request", patch=verb == "PUT")
        parameters.append(f"{request_type} request")
        test_args.append("default(JsonElement)" if request_type == "JsonElement" else "new()")
        request_arg = "EndpointTransport.Serialize(request)"
    else:
        request_arg = "null"
    options_type = "CloseListOptions" if is_offset_list else "CloseRequestOptions"
    parameters.extend([f"{options_type}? options = null", "CancellationToken cancellationToken = default"])
    test_args.append("cancellationToken: token")
    query = ("EndpointTransport.RequiredQuery(options, " + ", ".join(
        "(" + literal(key) + ", " + camel(key) + ")" for key in required_query
    ) + ")") if required_query else "options?.ToQuery()"
    http = "HttpMethod." + verb.title()
    arguments = f"{http}, {path}, {query}, {request_arg}, cancellationToken"
    api = "Transport" if group in {"Leads", "Tasks"} else "transport"
    if is_offset_list:
        item = models.shape_type(response_fields["data"].get("items", {}), name + "Item")
        page = f"ClosePage<{item}>"
        models.register.add(page)
        return_type = f"Task<{page}>"
        call = f"EndpointTransport.ListPageAsync<{item}>({api}, {path}, options, cancellationToken)"
        fixture = literal('{"data":[],"has_more":false}')
    elif success is None:
        return_type = "Task"
        call = f"EndpointTransport.SendWithoutBodyAsync({api}, {arguments})"
        fixture = "null"
    else:
        response_type = models.contract(response_shape, name + "Response")
        return_type = f"Task<{response_type}>"
        call = f"EndpointTransport.SendAsync<{response_type}>({api}, {arguments})"
        fixture = literal("[]" if response_type.startswith("IReadOnlyList") else
                          '"example"' if response_type == "string" else
                          "1" if response_type in {"int", "long", "decimal"} else
                          "false" if response_type == "bool" else
                          '"2026-01-01"' if response_type == "DateOnly" else
                          '"2026-01-01T00:00:00Z"' if response_type == "DateTimeOffset" else "{}")
    summary = (f'    /// <summary>Calls <see href="{reference}">{verb} {route}</see>.</summary>\n')
    if filter_type:
        summary += f'    /// <remarks>Pass <see cref="{filter_type}"/> for typed filters.</remarks>\n'
    for wire in required_query:
        summary += f'    /// <param name="{camel(wire)}">Required Close {wire} query parameter.</param>\n'
    if required_query:
        # Parameter docs are useful here, but document every parameter to satisfy XML-doc validation.
        summary += "".join(f'    /// <param name="{camel(wire)}">Close path parameter.</param>\n' for wire in variables)
        if request:
            summary += '    /// <param name="request">Close request body.</param>\n'
        summary += ('    /// <param name="options">Additional query options.</param>\n'
                    '    /// <param name="cancellationToken">Cancellation token.</param>\n')
    method_source = f"{summary}    public {return_type} {method}({', '.join(parameters)}) =>\n        {call};"
    if is_offset_list:
        method_source += (
            "\n\n    /// <summary>Streams the results forward, one page at a time.</summary>\n"
            f"    public IAsyncEnumerable<{item}> {stream_method}({', '.join(parameters)}) =>\n"
            f"        EndpointTransport.StreamAsync<{item}>({api}, {path}, options, cancellationToken);"
        )

    sample_route = route
    for variable in variables:
        sample_route = sample_route.replace("{" + variable + "}", "test_" + variable)
    expected_query = literal("&".join(key + "=test_" + key for key in required_query)) if required_query else "null"
    sample = f'new({literal(operation_id)}, {http}, {literal(sample_route)}, {"true" if request else "false"}, ' \
             f'{fixture}, {expected_query}, (sdk, token) => sdk.{group}.{method}({", ".join(test_args)}))'
    return group, method, method_source, sample


def render_clients(groups):
    lines = [HEADER.rstrip(), "using System.Text.Json;", "using ApiModels = Close.DotNet.Models;", "", "namespace Close.DotNet;", "",
             "public sealed partial class CloseClient", "{"]
    for group in sorted(groups.keys() | {"Files"}):
        if group in {"Leads", "Tasks", "Users"}:
            continue
        field = camel(group)
        lines.extend([
            f"    private {group}Client? {field};",
            f"    /// <summary>Close {group} operations.</summary>",
            f"    public {group}Client {group} => LazyInitializer.EnsureInitialized(ref {field}, () => new {group}Client(transport));",
            ""
        ])
    lines.extend(["}", ""])
    for group, methods in sorted(groups.items()):
        if group not in MANUAL_GROUPS:
            lines.append(f"/// <summary>API operations for {group}.</summary>")
            if group == "Exports":
                lines.extend([f"public sealed partial class {group}Client", "{", "    private readonly CloseTransport transport;",
                              f"    internal {group}Client(CloseTransport transport) => this.transport = transport;", ""])
            else:
                lines.extend([f"public sealed class {group}Client", "{", "    private readonly CloseTransport transport;",
                              f"    internal {group}Client(CloseTransport transport) => this.transport = transport;", ""])
        else:
            lines.extend([f"public sealed partial class {group}Client", "{"])
        lines.extend(["\n\n".join(methods), "}", ""])
    return "\n".join(lines)


def render_tests(cases):
    return (
        HEADER + "using System.Text.Json;\n\nnamespace Close.DotNet.Tests;\n\n"
        "public sealed partial class GeneratedEndpointContractTests\n{\n"
        "    private static readonly Contract[] Contracts =\n    [\n        " +
        ",\n        ".join(sorted(cases)) + "\n    ];\n}\n"
    )


def main():
    arg = argparse.ArgumentParser(description=__doc__)
    arg.add_argument("openapi", type=Path, help="Local copy of https://api.close.com/api/openapi.json")
    arg.add_argument("--check", action="store_true", help="Check regenerated files instead of updating them.")
    options = arg.parse_args()
    spec = json.loads(options.openapi.read_text(encoding="utf-8"))
    with COVERAGE.open(newline="", encoding="utf-8") as source:
        reader = csv.DictReader(source)
        rows = list(reader)
        columns = reader.fieldnames

    models = Models(spec["components"]["schemas"])
    query_options = QueryOptions(spec, pascal, group_name, method_name, literal)
    groups, cases = defaultdict(list), []
    pending_operations = [(row, op) for row, op in operations(spec, rows)
                          if not row["sdk_method"] or row["generation"] == "generated"]
    for row, operation in pending_operations:
        if row["method"] != "PUT":
            continue
        schema = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {})
        if "$ref" in schema:
            models.patch_components.add(schema["$ref"].rsplit("/", 1)[1])

    for row, op in operations(spec, rows):
        if row["generation"] == "manual":
            query_options.add_operation(row, op, row["operation_id"] in CORE_OFFSET_LISTS)

    for row, op in pending_operations:
        group, method, source, test = build_operation(row, op, models, query_options)
        groups[group].append(source)
        cases.append(test)
        row["sdk_method"] = group + "." + method
        row["generation"] = "generated"
    for row in rows:
        if row["operation_id"] in MANUAL_METHODS:
            row["sdk_method"] = MANUAL_METHODS[row["operation_id"]]

    outputs = {
        LIBRARY / "EndpointClients.g.cs": render_clients(groups),
        LIBRARY / "EndpointQueryOptions.g.cs": query_options.render(HEADER),
        LIBRARY / "EndpointModels.g.cs": models.records(),
        LIBRARY / "EndpointJson.g.cs": models.json_context(),
        TESTS / "GeneratedEndpointContracts.g.cs": render_tests(cases),
    }
    if options.check:
        for output, expected in outputs.items():
            if output.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Regenerate {output.name}.")
    else:
        for output, content in outputs.items():
            output.write_text(content, encoding="utf-8")
        with COVERAGE.open("w", newline="", encoding="utf-8") as output:
            writer = csv.DictWriter(output, fieldnames=columns, lineterminator="\n")
            writer.writeheader()
            writer.writerows(rows)


if __name__ == "__main__":
    main()
